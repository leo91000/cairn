// Regenerate the Gmail v1 catalog from Google's discovery document. Runtime code
// never fetches schemas or executes provider-supplied code.
import { readFile, writeFile } from 'node:fs/promises'
import process from 'node:process'

const source = 'https://gmail.googleapis.com/$discovery/rest?version=v1'
const discovery = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], 'utf8'))
  : await (await fetch(source)).json()
if (discovery.name !== 'gmail' || discovery.version !== 'v1')
  throw new Error('Expected the Google Gmail v1 discovery document')

const methods = {}

function collect(resource) {
  for (const method of Object.values(resource.methods || {})) {
    const operation = method.id.replace(/^gmail\./, '')
    methods[operation] = {
      method: method.httpMethod,
      path: method.path,
      description: method.description,
      parameters: method.parameters || {},
      request: method.request?.$ref,
      response: method.response?.$ref,
      scopes: method.scopes || [],
    }
  }

  for (const child of Object.values(resource.resources || {}))
    collect(child)
}

collect(discovery)

const metadata = {
  source,
  revision: discovery.revision,
  methods: Object.fromEntries(Object.entries(methods).sort(([a], [b]) => a.localeCompare(b))),
  parameters: discovery.parameters,
  schemas: discovery.schemas,
}
// A long string avoids interpreting quotes/backslashes in provider descriptions.
const json = JSON.stringify(metadata)
if (json.includes(']====]'))
  throw new Error('Unexpected long-string delimiter in discovery data')
await writeFile('plugins/gmail/catalog.luau', `-- Generated by scripts/generate-gmail-methods.mjs from ${source}\nreturn cairn.json.decode([====[${json}]====])\n`)
console.log(`Gmail ${metadata.revision}: ${Object.keys(methods).length} REST methods`)
