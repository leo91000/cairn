function writeInstallationClient(client) {
  const tsOutput = client.array ? `${client.output}[]` : client.output
  const ktOutput = client.array ? `List<${client.output}>` : client.output
  const hasBody = ['POST', 'PUT'].includes(client.method) || client.name === 'deleteChat'

  const queryFields = client.query ?? []
  const optionalQuery = client.optionalQuery ?? []
  const tsQueryFields = queryFields.map(field => optionalQuery.includes(field)
    ? `...(input.${field} == null ? {} : { ${field}: String(input.${field}) })`
    : `${field}: String(input.${field})`).join(', ')
  const tsQuerySetup = optionalQuery.length ? `  const query = new URLSearchParams({ ${tsQueryFields} }).toString()\n` : ''
  const tsQuery = queryFields.length
    ? optionalQuery.length
      // These interpolations belong to the generated clients.
      // eslint-disable-next-line no-template-curly-in-string
      ? '${query ? `?${query}` : \'\'}'
      : `?\${new URLSearchParams({ ${tsQueryFields} }).toString()}`
    : ''
  const tsPath = client.path.replace(/\{(\w+)\}/g, (_, field) => `\${encodeURIComponent(input.${field})}`) + tsQuery
  const tsConst = client.idConst ? `export const ${client.idConst.name} = '${client.idConst.value}' as const\n\n` : ''
  const tsFile = client.tsFile ?? `${client.name}.ts`
  writeFileSync(path.join(generated, tsFile), `// Generated by pnpm generate:contracts. Do not edit.
import type { ${client.input} } from './typescript/${client.input}'
${client.output === client.input ? '' : `import type { ${client.output} } from './typescript/${client.output}'`}

${tsConst}export function ${client.name}(request: <T>(path: string, options: RequestInit) => Promise<T>, ${!client.path.includes('{') && !hasBody && !queryFields.length ? '_input' : 'input'}: ${client.input}): Promise<${tsOutput}> {
${tsQuerySetup}  return request<${tsOutput}>(\`${tsPath}\`, { method: '${client.method}'${hasBody ? `, body: JSON.stringify(input${client.bodyField ? `.${client.bodyField}` : ''})` : ''} })
}
`)

  const ktQuery = queryFields.length
    ? optionalQuery.length
      // eslint-disable-next-line no-template-curly-in-string
      ? '${if (query.isEmpty()) "" else "?$query"}'
      : `?${queryFields.map(field => `${field}=\${segment(input.${field}.toString())}`).join('&')}`
    : ''
  const ktPath = client.path.replace(/\{(\w+)\}/g, (_, field) => `\${segment(input.${field})}`) + ktQuery
  const ktCall = client.deferred
    ? `wireJson.decodeFromJsonElement(pluginOperation("${ktPath}"${hasBody ? `, contractJson.encodeToJsonElement(input${client.bodyField ? `.${client.bodyField}` : ''})` : ''}, method = "${client.method}"))`
    : `send("${client.method}", "${ktPath}"${hasBody ? `, contractJson.encodeToJsonElement(input${client.bodyField ? `.${client.bodyField}` : ''})` : ''})`
  const ktQueryItems = queryFields.map(field => optionalQuery.includes(field)
    ? `input.${field}?.let { "${field}" to it.toString() }`
    : `"${field}" to input.${field}.toString()`).join(', ')
  const ktBody = optionalQuery.length
    ? ` {\n    val query = listOfNotNull(${ktQueryItems}).joinToString("&") { (key, value) -> "$key=\${segment(value)}" }\n    return ${ktCall}\n}\n`
    : ` =\n    ${ktCall}\n`
  const ktConst = client.idConst ? `const val ${client.idConst.name} = "${client.idConst.value}"\n\n` : ''
  writeFileSync(path.join(kotlin, `${client.name[0].toUpperCase()}${client.name.slice(1)}Client.kt`), `// Generated by pnpm generate:contracts. Do not edit.
package build.cairn.contracts

import build.cairn.app.data.CairnApi${client.path.includes('{') || queryFields.length ? '\nimport build.cairn.app.data.segment' : ''}
${client.deferred ? 'import build.cairn.app.data.wireJson\n' : ''}${client.deferred ? 'import build.cairn.app.data.pluginOperation\nimport kotlinx.serialization.json.decodeFromJsonElement\n' : ''}${hasBody ? 'import kotlinx.serialization.json.encodeToJsonElement\n' : ''}
${ktConst}suspend fun CairnApi.${client.name}(input: ${client.input}): ${ktOutput}${ktBody}`)
}

function writeBeaconAccountClient({
  name,
  tsFile,
  output,
  path: routePath,
}) {
  const route = routePath.slice('/api/account/'.length)
  writeFileSync(path.join(generated, tsFile), `// Generated by pnpm generate:contracts. Do not edit.
import type { ${output} } from './typescript/${output}'

// The caller supplies the authenticated Beacon account transport.
export function ${name}(request: <T>(route: string) => Promise<T>): Promise<${output}> {
  return request<${output}>('${route}')
}
`)
  writeFileSync(path.join(kotlin, `${name[0].toUpperCase()}${name.slice(1)}Client.kt`), `// Generated by pnpm generate:contracts. Do not edit.
package build.cairn.contracts

import build.cairn.app.data.CairnApi

suspend fun CairnApi.${name}(): ${output} =
    get("/account/${route}")
`)
}

