import { execFileSync } from 'node:child_process'
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const generated = path.join(root, 'packages/contracts/generated')
const kotlin = path.join(root, 'apps/android/app/src/main/java/build/cairn/contracts')
const run = (command, args, cwd = root) => execFileSync(command, args, { cwd, stdio: 'inherit' })
rmSync(generated, { recursive: true, force: true })
rmSync(kotlin, { recursive: true, force: true })
run('cargo', ['run', '--locked', '-p', 'cairn-contracts', '--example', 'export', '--', generated])
const definition = JSON.parse(readFileSync(path.join(generated, 'resume-run.json'), 'utf8'))
writeFileSync(path.join(generated, 'resume-run.ts'), `// Generated by scripts/generate-contracts.mjs. Do not edit.
import type { ResumeRunInput } from './typescript/ResumeRunInput'
import type { ResumeRunOutput } from './typescript/ResumeRunOutput'

export const resumeRunId = '${definition.id}' as const

export function resumeRun(request: <T>(path: string, options: RequestInit) => Promise<T>, input: ResumeRunInput): Promise<ResumeRunOutput> {
  return request<ResumeRunOutput>(\`${definition.path.replace('{runId}', `\${encodeURIComponent(input.runId)}`)}\`, { method: 'POST' })
}
`)
run(path.join(root, 'apps/android/gradlew'), ['-p', 'scripts/contracts-kotlin', 'run', `--args=${path.join(generated, 'models.json')} ${path.join(root, 'apps/android/app/src/main/java')}`, '--no-daemon'])
writeFileSync(path.join(kotlin, 'ResumeRunClient.kt'), `// Generated by scripts/generate-contracts.mjs. Do not edit.
package build.cairn.contracts

import build.cairn.app.data.CairnApi
import build.cairn.app.data.segment

const val resumeRunId = "${definition.id}"

suspend fun CairnApi.resumeRun(input: ResumeRunInput): ResumeRunOutput =
    send("POST", "${definition.path.replace('{runId}', `\${segment(input.runId)}`)}")
`)
// The same pinned formatters used by the repository; generated models are never patched.
run('pnpm', ['exec', 'eslint', 'packages/contracts/generated', '--fix'])
run(path.join(root, 'apps/android/gradlew'), ['-p', 'scripts/contracts-kotlin', 'formatClient', '--no-daemon'])
if (process.argv.includes('--check')) {
  const paths = ['packages/contracts/generated', 'apps/android/app/src/main/java/build/cairn/contracts']
  run('git', ['diff', '--exit-code', '--', ...paths])
  const untracked = execFileSync('git', ['ls-files', '--others', '--exclude-standard', '--', ...paths], { cwd: root, encoding: 'utf8' })
  if (untracked.trim())
    throw new Error(`Untracked generated contracts:\n${untracked}`)
}
