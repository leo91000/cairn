import {
  signIn as authenticateWorkspace,
  createAgent,
  expect,
  expectSingleScroll,
  grantFullAccess,
  initializeRepository,
  openAgentSection,
  test,
  workspacePath,
} from './fixtures'

test('selects live models and supported reasoning for agents and queued chat turns', async ({ page, workspace }, testInfo) => {
  test.setTimeout(60000)
  initializeRepository(workspace.projectPath)
  await page.goto(workspacePath('/'))
  await authenticateWorkspace(page)
  await expect(page.locator('.shell')).toBeVisible()
  await page.goto(workspacePath('/agents'))
  await page.getByRole('link', { name: 'New agent', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Model explorer')
  await grantFullAccess(page)
  await openAgentSection(page, 'Coding agent & model')
  const picker = page.getByRole('button', { name: /^Agent, model, reasoning and speed/ })
  const menu = page.getByRole('dialog', { name: 'Agent & model' })
  const reasoning = menu.getByRole('radiogroup', { name: 'Reasoning' })
  const effort = (name: string) => reasoning.getByRole('radio', { name, exact: true })
  // A new profile uses the same high effort as the generated server and Android defaults.
  await expect(picker).toHaveAccessibleName('Agent, model, reasoning and speed: Codex · Quick coder · High reasoning')
  await picker.click()
  await expect(menu.getByRole('radio', { name: 'Deep thinker', exact: true })).toBeVisible()
  await expect(menu.getByRole('radio', { name: 'Quick coder', exact: true })).toHaveCount(1)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: testInfo.outputPath('models-agent-desktop-light.png'), animations: 'disabled' })
  await menu.getByRole('radio', { name: 'Deep thinker', exact: true }).click()
  await expect(effort('High')).toHaveCount(0)
  await effort('Ultra').click()
  await menu.getByRole('radio', { name: 'Quick coder', exact: true }).click()
  await expect(effort('Model default · Low')).toHaveAttribute('aria-checked', 'true')
  await expect(effort('Ultra')).toHaveCount(0)
  await menu.getByRole('radio', { name: 'Deep thinker', exact: true }).click()
  await effort('Ultra').click()
  await menu.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(picker).toHaveAccessibleName('Agent, model, reasoning and speed: Codex · Deep thinker · Ultra reasoning')
  await createAgent(page)
  const agent = workspace.service.store.list('agents').find(agent => agent.name === 'Model explorer')!
  expect(agent.model).toBe('fixture-deep')
  expect(agent.reasoning).toBe('ultra')
  await page.getByRole('link', { name: 'Chat with this agent' }).click()
  await picker.click()
  await expect(effort('Agent default · Ultra')).toHaveAttribute('aria-checked', 'true')
  await menu.getByRole('radio', { name: 'Quick coder', exact: true }).click()
  await effort('High').click()
  await page.keyboard.press('Escape')
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Review the layout. fixture:chat-hang')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page).toHaveURL(/\/chats\/[a-z]+-[a-z]+-[a-f0-9]{8}$/)
  const chatKey = new URL(page.url()).pathname.split('/').at(-1)!
  const chatId = (await workspace.api(`/api/chats/${chatKey}`)).id
  await expect.poll(() => workspace.service.chats.detail(chatId).run?.status, { timeout: 30000 }).toBe('running')
  expect(workspace.service.chats.detail(chatId).run?.snapshot.agent).toMatchObject({ model: 'fixture-fast', reasoning: 'high' })
  await picker.click()
  await menu.getByRole('radio', { name: 'Deep thinker', exact: true }).click()
  await effort('Ultra').click()
  await page.keyboard.press('Escape')
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Investigate the keyboard shortcuts')
  await page.getByRole('button', { name: 'Queue', exact: true }).click()
  await page.getByRole('button', { name: /^Queued message options/ }).first().click()
  await page.getByRole('dialog', { name: 'Queued message' }).getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(picker).toHaveAccessibleName(/Deep thinker · Ultra reasoning$/)
  await picker.click()
  await expect(effort('Ultra')).toHaveAttribute('aria-checked', 'true')
  await effort('Medium').click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect.poll(() => workspace.service.chats.detail(chatId).messages.find(m => m.status === 'queued')).toMatchObject({ model: 'fixture-deep', reasoning: 'medium' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.getByText('Agent saved', { exact: true })).not.toBeVisible()
  await expectSingleScroll(page)
  await picker.click()
  await expect(effort('Ultra')).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('models-chat-mobile-dark.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 320, height: 600 })
  await expectSingleScroll(page)
  // With an empty field during a reply, the composer's round action stops the agent.
  await expect(page.getByRole('button', { name: 'Stop response', exact: true })).toBeInViewport()
  await workspace.api(`/api/chats/${chatId}/messages`, 'POST', { id: crypto.randomUUID(), text: 'finish now', mode: 'steer' })
  await expect.poll(() => workspace.service.chats.detail(chatId).run?.summary).toContain('Investigate the keyboard shortcuts')
  expect(workspace.service.chats.detail(chatId).run?.snapshot.agent).toMatchObject({ model: 'fixture-deep', reasoning: 'medium' })
})

test('keeps the Codex speed across models, for agents and queued chat turns', async ({ page, workspace }, testInfo) => {
  test.setTimeout(60000)
  initializeRepository(workspace.projectPath)
  await page.goto(workspacePath('/'))
  await authenticateWorkspace(page)
  await page.goto(workspacePath('/agents'))
  await page.getByRole('link', { name: 'New agent', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Speed explorer')
  await grantFullAccess(page)
  await openAgentSection(page, 'Coding agent & model')
  const picker = page.getByRole('button', { name: /^Agent, model, reasoning and speed/ })
  const menu = page.getByRole('dialog', { name: 'Agent & model' })
  const speeds = menu.getByRole('radiogroup', { name: 'Speed' })
  const speed = (name: string) => speeds.getByRole('radio', { name, exact: true })
  await picker.click()
  await expect(speed('Default · Standard')).toHaveAttribute('aria-checked', 'true')
  await speed('Fast').click()
  // Codex's own words for the speed's usage, and where OpenAI explains the rates.
  await expect(menu.getByText('1.5x speed, increased usage')).toBeVisible()
  await expect(menu.getByRole('link', { name: 'How speed uses your plan' })).toHaveAttribute('href', 'https://learn.chatgpt.com/docs/agent-configuration/speed')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: testInfo.outputPath('speed-agent-desktop-light.png'), animations: 'disabled' })
  await menu.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(picker).toHaveAccessibleName('Agent, model, reasoning and speed: Codex · Quick coder · High reasoning · Fast speed')
  await createAgent(page)
  const agent = workspace.service.store.list('agents').find(agent => agent.name === 'Speed explorer')!
  expect(agent.speed).toBe('priority')

  await page.getByRole('link', { name: 'Chat with this agent' }).click()
  await picker.click()
  await expect(speed('Agent default · Fast')).toHaveAttribute('aria-checked', 'true')
  // Another model keeps the speed but never claims one it does not offer.
  await menu.getByRole('radio', { name: 'Deep thinker', exact: true }).click()
  await expect(menu.getByText('This model doesn’t offer Fast.', { exact: false })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(picker).toHaveAccessibleName('Agent, model, reasoning and speed: Codex · Deep thinker · Medium reasoning')
  await picker.click()
  await speed('Standard').click()
  await page.keyboard.press('Escape')
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Review the speed. fixture:chat-hang')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page).toHaveURL(/\/chats\/[a-z]+-[a-z]+-[a-f0-9]{8}$/)
  const chatKey = new URL(page.url()).pathname.split('/').at(-1)!
  const chatId = (await workspace.api(`/api/chats/${chatKey}`)).id
  await expect.poll(() => workspace.service.chats.detail(chatId).run?.status, { timeout: 30000 }).toBe('running')
  expect(workspace.service.chats.detail(chatId).run?.snapshot.agent).toMatchObject({ model: 'fixture-deep', speed: 'standard' })

  // A queued message keeps its own speed, shown in the queue and restored when edited.
  await picker.click()
  await menu.getByRole('radio', { name: 'Quick coder', exact: true }).click()
  await speed('Fast').click()
  await page.keyboard.press('Escape')
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Then go faster')
  await page.getByRole('button', { name: 'Queue', exact: true }).click()
  await expect(page.getByTestId('queued-message')).toContainText('Fast speed')
  await expect.poll(() => workspace.service.chats.detail(chatId).messages.find(m => m.status === 'queued')).toMatchObject({ model: 'fixture-fast', speed: 'priority' })
  await page.getByRole('button', { name: /^Queued message options/ }).first().click()
  await page.getByRole('dialog', { name: 'Queued message' }).getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(picker).toHaveAccessibleName(/Quick coder · Low reasoning · Fast speed$/)
  await picker.click()
  await expect(speed('Fast')).toHaveAttribute('aria-checked', 'true')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(speed('Fast')).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('speed-chat-mobile-dark.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await workspace.api(`/api/chats/${chatId}/messages`, 'POST', { id: crypto.randomUUID(), text: 'finish now', mode: 'steer' })
  await expect.poll(() => workspace.service.chats.detail(chatId).run?.summary, { timeout: 30000 }).toContain('Then go faster')
  expect(workspace.service.chats.detail(chatId).run?.snapshot.agent).toMatchObject({ model: 'fixture-fast', speed: 'priority' })
})
